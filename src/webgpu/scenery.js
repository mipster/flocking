// Scenery model: rock formations (boulders, arches, caves), coral and seaweed on the sand.
//
// Solid things are described as a signed distance field (SDF): a handful of primitives (ellipsoids,
// capsules, a ring) blended with a smooth minimum, with other primitives carved out of them. An SDF
// is what makes arches and caves cheap: a cave is just a dome minus a tunnel. The same field can be
// meshed for drawing and sampled by the simulation for fish avoidance, so they always agree.
//
// Everything is plain data (no classes), generated from a seed, so it can be uploaded to a buffer,
// compared in tests and regenerated by changing the seed. The field repeats every tank width in x,
// matching the left/right wrap of the flock.
import { SCENERY } from './config.js';
import { floorY } from './floor.js';

/** Small seeded generator (mulberry32): same seed, same sequence, in every browser. */
export function makeRng(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Smooth minimum: like min(a, b) but blended over a band of width k. */
export function smoothMin(a, b, k) {
  const h = Math.max(k - Math.abs(a - b), 0) / k;
  return Math.min(a, b) - h * h * k * 0.25;
}

// --- primitives, in a feature's local space (origin on the sand) ---------------------------

function ellipsoid(x, y, z, { c, r }) {
  const px = (x - c[0]) / r[0];
  const py = (y - c[1]) / r[1];
  const pz = (z - c[2]) / r[2];
  const k0 = Math.sqrt(px * px + py * py + pz * pz);
  const k1 = Math.sqrt((px * px) / (r[0] * r[0]) + (py * py) / (r[1] * r[1]) + (pz * pz) / (r[2] * r[2]));
  return k1 > 1e-9 ? (k0 * (k0 - 1)) / k1 : -Math.min(r[0], r[1], r[2]);
}

function capsule(x, y, z, { a, b, r }) {
  const abx = b[0] - a[0];
  const aby = b[1] - a[1];
  const abz = b[2] - a[2];
  const apx = x - a[0];
  const apy = y - a[1];
  const apz = z - a[2];
  const len2 = abx * abx + aby * aby + abz * abz;
  const h = len2 > 0 ? Math.min(Math.max((apx * abx + apy * aby + apz * abz) / len2, 0), 1) : 0;
  const dx = apx - abx * h;
  const dy = apy - aby * h;
  const dz = apz - abz * h;
  return Math.sqrt(dx * dx + dy * dy + dz * dz) - r;
}

/** A vertical ring in the local x/y plane (axis along z): centre `c`, ring radius R, tube radius r. */
function ring(x, y, z, { c, R, r, depth }) {
  const dx = x - c[0];
  const dy = y - c[1];
  const dz = (z - c[2]) / depth; // depth < 1 thickens the ring front to back
  const q = Math.sqrt(dx * dx + dy * dy) - R;
  return Math.sqrt(q * q + dz * dz) * Math.min(1, depth) - r;
}

const PRIMITIVES = { ellipsoid, capsule, ring };

function evalParts(x, y, z, parts, smooth) {
  let d = Infinity;
  for (const part of parts) {
    const v = PRIMITIVES[part.shape](x, y, z, part);
    d = d === Infinity ? v : smoothMin(d, v, smooth);
  }
  return d;
}

/** Distance from world point (x, y, z) to one feature, which may be a lower bound far from it. */
export function featureDistance(f, x, y, z, width) {
  let dx = x - f.c[0];
  dx -= Math.round(dx / width) * width; // nearest copy of the tile
  const dy = y - f.c[1];
  const dz = z - f.c[2];
  const away = Math.sqrt(dx * dx + dy * dy + dz * dz) - f.radius;
  if (away > 4) return away; // far from the feature: skip the exact evaluation
  const c = Math.cos(f.yaw);
  const s = Math.sin(f.yaw);
  const lx = dx * c - dz * s;
  const lz = dx * s + dz * c;
  let d = evalParts(lx, dy, lz, f.parts, f.smooth);
  if (f.carves.length > 0) d = Math.max(d, -evalParts(lx, dy, lz, f.carves, f.smooth));
  return d;
}

// --- feature builders ------------------------------------------------------------------------

const range = (rng, lo, hi) => lo + (hi - lo) * rng();

function boulder(rng) {
  const parts = [];
  const lumps = 3 + Math.floor(rng() * 3);
  const size = range(rng, 3, 6);
  for (let i = 0; i < lumps; i++) {
    const r = size * range(rng, 0.55, 1);
    parts.push({
      shape: 'ellipsoid',
      c: [range(rng, -1, 1) * size * 0.8, r * 0.45, range(rng, -1, 1) * size * 0.8],
      r: [r, r * range(rng, 0.6, 0.9), r * range(rng, 0.8, 1.1)],
    });
  }
  return { parts, carves: [], radius: size * 2.6 };
}

function arch(rng) {
  const R = range(rng, 8, 12);
  const r = range(rng, 2.2, 3.4);
  const foot = r * 1.5;
  const parts = [
    { shape: 'ring', c: [0, 0, 0], R, r, depth: range(rng, 0.8, 1.3) },
    { shape: 'ellipsoid', c: [-R, 0, 0], r: [foot, foot * 0.9, foot] },
    { shape: 'ellipsoid', c: [R, 0, 0], r: [foot, foot * 0.9, foot] },
  ];
  return { parts, carves: [], radius: R + foot * 1.2 };
}

function cave(rng) {
  const rx = range(rng, 11, 16);
  const ry = range(rng, 7, 10);
  const rz = range(rng, 9, 12);
  const parts = [{ shape: 'ellipsoid', c: [0, 0, 0], r: [rx, ry, rz] }];
  for (let i = 0; i < 2; i++) {
    const r = range(rng, 0.4, 0.6) * ry;
    parts.push({
      shape: 'ellipsoid',
      c: [range(rng, -0.7, 0.7) * rx, ry * 0.5, range(rng, -0.7, 0.7) * rz],
      r: [r * 1.4, r, r * 1.2],
    });
  }
  // a tunnel straight through along local x, wide enough for the flock to swim into
  const tunnel = ry * 0.5;
  const carves = [
    { shape: 'capsule', a: [-rx * 1.3, tunnel * 0.4, 0], b: [rx * 1.3, tunnel * 0.4, 0], r: tunnel },
  ];
  return { parts, carves, radius: Math.max(rx, rz) * 1.25 };
}

function branchingCoral(rng) {
  const parts = [];
  let radius = 0;
  const grow = (from, dir, length, thick, depth) => {
    const to = [from[0] + dir[0] * length, from[1] + dir[1] * length, from[2] + dir[2] * length];
    parts.push({ shape: 'capsule', a: from, b: to, r: thick });
    radius = Math.max(radius, Math.hypot(to[0], to[1], to[2]) + thick);
    if (depth === 0) return;
    const kids = 2 + Math.floor(rng() * 2);
    for (let i = 0; i < kids; i++) {
      // tilt away from the parent direction, then pull back toward vertical so branches reach up
      const spin = range(rng, 0, Math.PI * 2);
      const tilt = range(rng, 0.4, 0.8);
      const side = [Math.cos(spin), 0, Math.sin(spin)];
      const k = [dir[0] + side[0] * Math.tan(tilt), dir[1] + 0.6, dir[2] + side[2] * Math.tan(tilt)];
      const n = Math.hypot(...k);
      grow(to, [k[0] / n, k[1] / n, k[2] / n], length * 0.72, thick * 0.72, depth - 1);
    }
  };
  grow([0, -0.5, 0], [0, 1, 0], range(rng, 2.4, 4), range(rng, 0.5, 0.75), 3);
  return { parts, carves: [], radius: radius + 1 };
}

function fanCoral(rng) {
  const h = range(rng, 3, 6);
  const w = h * range(rng, 0.7, 1.1);
  const parts = [
    { shape: 'capsule', a: [0, -0.5, 0], b: [0, h * 0.3, 0], r: 0.45 },
    { shape: 'ellipsoid', c: [0, h * 0.8, 0], r: [w, h * 0.75, 0.5] },
  ];
  return { parts, carves: [], radius: Math.hypot(w, h * 1.6) };
}

const BUILDERS = { cave, arch, boulder, branching: branchingCoral, fan: fanCoral };
const PLACEMENT_ORDER = ['cave', 'arch', 'boulder', 'branching', 'fan']; // big things claim space first

/** Horizontal distance between two points, with the x axis wrapping every `width`. */
function wrappedDistance(ax, az, bx, bz, width) {
  let dx = ax - bx;
  dx -= Math.round(dx / width) * width;
  return Math.hypot(dx, az - bz);
}

/**
 * Generates the scenery for a tank with half extents `half`.
 * Returns { features, seaweed, distance(x, y, z) }: `features` and `seaweed` are plain data;
 * `distance` is the signed distance to the nearest solid (negative inside rock or coral).
 */
export function generateScenery(half, { seed = SCENERY.seed, ...overrides } = {}) {
  const cfg = { ...SCENERY, ...overrides };
  const rng = makeRng(seed);
  const width = half[0] * 2;
  const zLimit = half[2] - cfg.margin;
  const floorArea = (width * zLimit * 2) / 10000;
  const features = [];

  const place = (radius) => {
    for (let attempt = 0; attempt < 40; attempt++) {
      const x = range(rng, -half[0], half[0]);
      const z = range(rng, -zLimit, zLimit);
      const clear = features.every(
        (f) => wrappedDistance(x, z, f.c[0], f.c[2], width) > f.radius + radius + cfg.gap
      );
      if (clear) return [x, z];
    }
    return null;
  };

  for (const kind of PLACEMENT_ORDER) {
    const count = Math.round(floorArea * cfg.density[kind]);
    for (let i = 0; i < count; i++) {
      const built = BUILDERS[kind](rng);
      const spot = place(built.radius);
      if (!spot) continue;
      features.push({
        kind,
        c: [spot[0], floorY(spot[0], spot[1], half), spot[1]],
        yaw: range(rng, 0, Math.PI * 2),
        tone: rng(), // picks a colour from the kind's palette
        smooth: cfg.smooth,
        ...built,
      });
    }
  }

  // seaweed grows in patches on open sand, away from rock and coral
  const seaweed = [];
  const patches = Math.round(floorArea * cfg.density.weedPatch);
  for (let i = 0; i < patches; i++) {
    const px = range(rng, -half[0], half[0]);
    const pz = range(rng, -zLimit, zLimit);
    const plants = 5 + Math.floor(rng() * 8);
    for (let j = 0; j < plants; j++) {
      const x = px + range(rng, -3, 3);
      const z = Math.min(zLimit, Math.max(-zLimit, pz + range(rng, -3, 3)));
      const blocked = features.some((f) => wrappedDistance(x, z, f.c[0], f.c[2], width) < f.radius * 0.8);
      if (blocked) continue;
      seaweed.push({
        x,
        y: floorY(x, z, half),
        z,
        height: range(rng, 4, 14),
        phase: range(rng, 0, Math.PI * 2),
      });
    }
  }

  const distance = (x, y, z) => {
    let d = Infinity;
    for (const f of features) d = Math.min(d, featureDistance(f, x, y, z, width));
    return d;
  };
  return { features, seaweed, distance };
}
